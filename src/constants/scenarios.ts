/** 파일명에서 뽑은 케이스 이름(`s01`, `S2`, …)으로 시나리오를 찾는다. 없으면 null. */
export function scenarioFromCaseName(caseName: string): FlowScenario | null {
  const m = /^s0*(\d{1,2})$/i.exec(caseName.trim());
  if (!m) return null;
  return FLOW_SCENARIOS.find((s) => s.index === Number(m[1])) ?? null;
}
